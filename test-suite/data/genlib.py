"""Shared helpers for the matrix generators (gen_*.py).

A generator creates a Matrix, adds one row per test case (the set of matrix
columns the case addresses, plus the case itself), and writes the matrix
markdown and the cases JSON. IDs are assigned in the order rows are added, so a
generator must append new combinations after existing ones to keep IDs stable.
"""
import json
from pathlib import Path

HERE = Path(__file__).parent


class Matrix:
    def __init__(self, mid, title, model, columns, description="", notes=None):
        self.mid, self.title, self.model = mid, title, model
        self.columns, self.description, self.notes = columns, description, notes or {}
        self.rows, self.cases = [], []

    def add(self, marks, check, element, expect, through=None, **extra):
        unknown = set(marks) - set(self.columns)
        assert not unknown, f"unknown columns {unknown}"
        cid = f"{self.mid}-{len(self.cases) + 1:03d}"
        self.rows.append((cid, set(marks)))
        case = {"id": cid, "check": check, "element": element, "expect": expect}
        if through:
            case["through"] = through
        case.update(extra)
        self.cases.append(case)
        return cid

    def write(self, generator):
        cols = self.columns
        md = [f"### Matrix {self.mid} - {self.title}", ""]
        if self.description:
            md.append(self.description)
        md += [f"Model: `data/{self.model}`. Expected values: `data/cases/{self.mid}.json`.",
               f"Generated by `data/{generator}`; edit the generator, not this file.", "",
               "|ID|" + "|".join(cols) + "|", "|--|" + "|".join(":-:" for _ in cols) + "|"]
        for cid, marks in self.rows:
            md.append(f"|{cid}|" + "|".join("x" if c in marks else " " for c in cols) + "|")
        (HERE / "matrices" / f"{self.mid}.md").write_text("\n".join(md) + "\n")
        spec = {"matrix": self.mid, "model": self.model, "notes": self.notes, "cases": self.cases}
        (HERE / "cases" / f"{self.mid}.json").write_text(json.dumps(spec, indent=1) + "\n")
        print(f"{self.mid}: {len(self.cases)} cases")
