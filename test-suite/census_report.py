#!/usr/bin/env python3
"""Tabulate the derived-property census: results/census-<suite>.json, written by run-census.sh.

  ./census_report.py      Markdown on stdout (run-census.sh writes it to results/census-report.md)

The property list and the corpora come from data/census/derived-properties.json
(data/gen_census.py, from the Pilot's SysML.ecore). Each census adapter counts, per derived
property and metaclass, the elements of a corpus that carry the property and how many of
them the MDK answers with a value, answers empty, or does not answer. The Pilot is the
reference column: a property is compared over the metaclasses both MDKs have elements of.
"""
import contextlib
import io
import json
from collections import defaultdict
from pathlib import Path

from report import print_versions

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
SPEC = json.loads((HERE / "data/census/derived-properties.json").read_text())
REFERENCE = "pilot-java"
ORDER = ["pilot-java", "sysml-toolkit-rs", "opensysml-go-props"]
GAP = 0.25  # a fill rate this much below or above the reference is listed


def load():
    out = {}
    for s in ORDER:
        f = RESULTS / f"census-{s}.json"
        if f.exists():
            out[s] = json.loads(f.read_text())
    return out


def totals(counts, metaclasses=None):
    """carriers, non-empty, empty, unanswered, error over metaclasses (all when None)."""
    t = [0] * 5
    for mc, n in counts.items():
        if metaclasses is None or mc in metaclasses:
            t = [a + b for a, b in zip(t, n)]
    return t


def cell(t):
    carriers, full, empty, unanswered, error = t
    if carriers == 0:
        return ""
    if unanswered + error == carriers:
        return "unanswered" if error == 0 else "error"
    s = f"{full}/{carriers - unanswered - error}"
    if unanswered or error:
        s += f" ({unanswered + error} unanswered)"
    return s


def rate(t):
    answered = t[0] - t[3] - t[4]
    return t[1] / answered if answered else None


def compare(ref, other):
    """(kind, detail) for an MDK's counts against the reference's, over common metaclasses."""
    common = set(ref) & set(other)
    r, o = totals(ref, common), totals(other, common)
    if r[0] == 0 or o[0] == 0:
        return None
    if o[3] + o[4] == o[0]:
        return ("unanswered", f"{o[0]} elements")
    rr, ro = rate(r), rate(o)
    if rr is None:
        return None
    if rr > 0 and o[1] == 0:
        return ("always empty", f"reference fills {r[1]}/{r[0] - r[3] - r[4]}; answered empty on all {o[0] - o[3] - o[4]}")
    if ro is not None and ro < rr - GAP:
        return ("fills less", f"{ro:.0%} vs {rr:.0%} ({o[1]}/{o[0] - o[3] - o[4]} vs {r[1]}/{r[0] - r[3] - r[4]})")
    if ro is not None and ro > rr + GAP:
        return ("fills more", f"{ro:.0%} vs {rr:.0%} ({o[1]}/{o[0] - o[3] - o[4]} vs {r[1]}/{r[0] - r[3] - r[4]})")
    return None


def main():
    data = load()
    suites = [s for s in ORDER if s in data]
    versions = {}
    for s in suites:
        vf = RESULTS / f"census-{s}.version.json"
        if vf.exists():
            versions[s] = json.loads(vf.read_text())
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        print_versions(suites, versions)
    print(buf.getvalue().replace("# SysML v2 MDK test results", "# SysML v2 derived-property census", 1), end="")

    src = SPEC["source"]
    print("## What this is")
    print()
    print(f"Every derived property of the metamodel ({len(SPEC['properties'])} properties marked "
          f"`derived=\"true\"` in the Pilot's `{src['file']}`, commit `{src['pilotCommit'][:10]}`, "
          f"{src['nsURI']}) is read on every element of each corpus that carries it. A cell is "
          "`values/answered`: how many of the carrying elements the MDK answers with a non-empty "
          "value, out of those it answers at all; `unanswered` means the MDK does not derive the "
          "property (it says so, or it raises). The element set is the corpus as written: each "
          "document's root namespace, its owned relationships that are not implied, and their "
          "owned related elements, transitively.")
    print()
    print("An empty value is not wrong in itself (a part def with no features has an empty "
          "`ownedFeature`). The signal is the comparison: the Pilot, the OMG reference "
          "implementation, is the reference column, and a property is compared over the "
          "metaclasses both MDKs have elements of, so that an element one MDK creates and another "
          "does not (see Element sets) does not move the other's rate. "
          f"Listed below: properties an MDK does not answer, answers empty where the reference "
          f"has values, or fills at a rate more than {GAP:.0%} below or above the reference's.")
    print()
    print("Generated by `census_report.py` from `results/census-<suite>.json` (`run-census.sh`). "
          "Property list and corpora: `data/census/derived-properties.json` (`data/gen_census.py`).")
    print()

    corpora = list(SPEC["corpora"])
    print("## Corpora")
    print()
    print("|corpus|files|" + "|".join(f"{s}: elements" for s in suites) + "|files left out|")
    print("|--|--:|" + "|".join("--:" for _ in suites) + "|--|")
    for c in corpora:
        left = [f"{Path(f).name} (all: {why.split(', as')[0]})" for f, why in SPEC["excluded"].get(c, {}).items()]
        for s in suites:
            for f, why in (data[s]["corpora"].get(c, {}).get("excludedByMdk") or {}).items():
                left.append(f"{Path(f).name} ({s}: {why})".replace("|", "\\|"))
        cells = [str(data[s]["corpora"].get(c, {}).get("elements", "")) for s in suites]
        print(f"|{c}|{len(SPEC['corpora'][c])}|" + "|".join(cells) + "|" + "<br>".join(left) + "|")
    print()

    # summary per suite and corpus
    print("## Summary")
    print()
    print("Properties, of those carried by some element of the corpus: answered with values on at "
          "least one element / answered but always empty / not answered.")
    print()
    print("|corpus|" + "|".join(suites) + "|")
    print("|--|" + "|".join(":-:" for _ in suites) + "|")
    for c in corpora:
        row = []
        for s in suites:
            counts = data[s]["corpora"].get(c, {}).get("counts", {})
            k = [0, 0, 0]
            for key, byMeta in counts.items():
                t = totals(byMeta)
                if t[0] == 0:
                    continue
                if t[3] + t[4] == t[0]:
                    k[2] += 1
                elif t[1] == 0:
                    k[1] += 1
                else:
                    k[0] += 1
            row.append(f"{k[0]} / {k[1]} / {k[2]}")
        print(f"|{c}|" + "|".join(row) + "|")
    print()

    print("## Differences from the reference")
    print()
    for c in corpora:
        print(f"### {c}")
        print()
        ref = data.get(REFERENCE, {}).get("corpora", {}).get(c, {}).get("counts", {})
        for s in suites:
            if s == REFERENCE:
                continue
            other = data[s]["corpora"].get(c, {}).get("counts", {})
            found = defaultdict(list)
            for key in SPEC["properties"]:
                d = compare(ref.get(key, {}), other.get(key, {}))
                if d:
                    found[d[0]].append((key, d[1]))
            n = sum(len(v) for v in found.values())
            print(f"**{s}**: {n} properties")
            print()
            if not n:
                continue
            print("|property|difference|detail|note|")
            print("|--|--|--|--|")
            notes = data[s]["corpora"].get(c, {}).get("notes", {})
            for kind in ["unanswered", "always empty", "fills less", "fills more"]:
                for key, detail in found.get(kind, []):
                    note = notes.get(key, "").replace("|", "\\|")
                    print(f"|`{key}`|{kind}|{detail}|{note}|")
            print()

    print("## Element sets")
    print()
    print("Elements per metaclass where the MDKs differ by more than 10% (largest differences "
          "first). The census compares over common metaclasses, so these do not move the rates, "
          "but they are differences in the abstract syntax each MDK builds from the same text.")
    print()
    for c in corpora:
        per = {s: {mc: n[0] for mc, n in data[s]["corpora"].get(c, {}).get("counts", {}).get("Element::owner", {}).items()}
               for s in suites}
        mcs = sorted(set().union(*per.values()))
        rows = []
        for mc in mcs:
            vals = [per[s].get(mc, 0) for s in suites]
            if max(vals) and (max(vals) - min(vals)) / max(vals) > 0.10:
                rows.append((max(vals) - min(vals), mc, vals))
        rows.sort(key=lambda r: (-r[0], r[1]))
        print(f"### {c}")
        print()
        print("|metaclass|" + "|".join(suites) + "|")
        print("|--|" + "|".join("--:" for _ in suites) + "|")
        for _, mc, vals in rows[:25]:
            print(f"|{mc}|" + "|".join(str(v) for v in vals) + "|")
        if len(rows) > 25:
            print(f"|({len(rows) - 25} more)|" + "|".join("" for _ in suites) + "|")
        print()

    print("## All properties")
    print()
    for c in corpora:
        print(f"### {c}")
        print()
        print("|property|" + "|".join(suites) + "|")
        print("|--|" + "|".join(":-:" for _ in suites) + "|")
        for key in SPEC["properties"]:
            cells = [cell(totals(data[s]["corpora"].get(c, {}).get("counts", {}).get(key, {}))) for s in suites]
            if any(cells):
                print(f"|`{key}`|" + "|".join(cells) + "|")
        absent = [k for k in SPEC["properties"]
                  if not any(data[s]["corpora"].get(c, {}).get("counts", {}).get(k) for s in suites)]
        print()
        if absent:
            print(f"Not carried by any element of this corpus: {', '.join(f'`{k}`' for k in absent)}.")
            print()


if __name__ == "__main__":
    main()
